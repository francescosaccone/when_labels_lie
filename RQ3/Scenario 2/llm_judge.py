import pandas as pd
import requests
import json
import time
import os
import re

"""
Run an LLM-as-a-judge pipeline on correctly classified issue examples.

This script processes a CSV file containing GitHub issues whose assigned label
must be evaluated by a local Ollama language model. The input file is defined by
INPUT_FILE and should contain the issue URL, title, body, the label given to the
model, and the correct label.

For each issue, the script builds a prompt asking the configured model to judge
whether the provided label is appropriate for the issue. The model must answer
with a yes/no judgment, where "yes" means that the assigned label is appropriate
and "no" means that the assigned label is not appropriate.

The model can be changed through OLLAMA_MODEL, while the Ollama endpoint is
defined by OLLAMA_URL. The output CSV file is defined by OUTPUT_FILE and should
be changed according to the model or dataset being evaluated.

The output CSV contains the original issue fields, the label information, the
LLM judgment in the risposta_LLM column, and a model_error field reporting
parsing or request errors.
"""





INPUT_FILE = "out_step_2/judge_input_correct.csv"
OUTPUT_FILE = "out_step_3/judge_output_correct_llama3.csv"

OLLAMA_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = "koesn/llama3-8b-instruct"

URL_COL = "issue_URL"
TITLE_COL = "issue_title"
BODY_COL = "issue_body"
LABEL_GIVEN_COL = "label_given_to_model"
GROUNDTRUTH_COL = "correct_label"

REQUEST_TIMEOUT = 300
SLEEP_SECONDS = 0.1

os.makedirs("out_step_3", exist_ok=True)

LABEL_LIST = ["bug", "enhancement", "question"]

LABEL_DESCRIPTION = """
The "bug" label is used to identify an issue report that describes a problem or error within the software or codebase. It indicates that something is not functioning as intended or producing unexpected results. Bug reports help developers identify and fix issues to improve the overall quality and reliability of the software.

The "enhancement" label indicates new feature requests. It indicates that the reported issue is not related to a clear problem or bug, but rather an opportunity to add functionality or improve the existing behavior, usability, or performance. Enhancement requests help developers prioritize valuable additions and evolve the software over time.

The "question" label is used when a user or contributor has a query or needs clarification regarding the software or codebase. It indicates that the issue report is seeking information, guidance, or assistance. Questions can be related to functionality, usage, best practices, or any other topic that requires clarification.
"""

def build_prompt(title: str, body: str, assigned_label: str) -> str:
    """
    Build the prompt used to ask the model whether an assigned label is appropriate.
    Parameters
    ----------
    title : str
        GitHub issue title.
    body : str
        GitHub issue body.
    assigned_label : str
        Label assigned to the issue and evaluated by the model.
    Returns
    -------
    str
        Prompt to send to the local Ollama model.
    """
    prompt = f"""
You are provided with a GitHub issue in this format:
TITLE: \"\"\"{title}\"\"\"

BODY: \"\"\"{body}\"\"\"

ASSIGNED LABEL: \"\"\"{assigned_label}\"\"\"

You have to judge whether the assigned label is appropriate for the issue.
Possible labels are: {LABEL_LIST}

{LABEL_DESCRIPTION}

Title: \"\"\"{title}\"\"\"
Body: \"\"\"{body}\"\"\"
Assigned label: \"\"\"{assigned_label}\"\"\"

Return ONLY a markdown JSON snippet exactly in this format:

```json
{{
  "judgment": "yes"
}}
Use:

“yes” if the assigned label is appropriate
“no” if the assigned label is not appropriate
""".strip()
    return prompt



def query_ollama(prompt: str) -> str:
    """
    Send a prompt to the local Ollama model and return the generated text.
    Parameters
    ----------
    prompt : str
    Prompt to send to Ollama.
    Returns
    ------- 
    str
    Raw text response generated by the model.    
    """
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0
        }
    }

    response = requests.post(
        OLLAMA_URL,
        json=payload,
        timeout=REQUEST_TIMEOUT
    )

    
    response.raise_for_status()

    data = response.json()
    import pprint
    print("\nMODEL TEXT RESPONSE")
    print(data.get("response", ""))
    return data.get("response", "").strip()



def extract_judgment(raw_output: str) -> str:
    """
    Extract a yes/no judgment from the model output.
    The function first tries to parse JSON objects inside markdown code blocks or plain JSON text. 
    If JSON parsing fails, it applies fallback regular expressions to identify explicit yes/no judgments.
    Parameters
    ----------
    raw_output : str
    Raw text generated by the model.
    Returns
    -------
    str
    Extracted judgment, either "yes" or "no". Returns an empty string if no
    valid judgment can be parsed.
    """

    allowed_judgments = {"yes", "no"}

    if raw_output is None:
        return ""

    if not isinstance(raw_output, str):
        raw_output = str(raw_output)

    text = raw_output.strip()
    if not text:
        return ""

    json_patterns = [
        r"```json\s*(\{.*?\})\s*```",
        r"```\s*(\{.*?\})\s*```",
        r"(\{.*?\})"
    ]

    for pattern in json_patterns:
        matches = re.findall(pattern, text, re.DOTALL)
        for json_text in matches:
            try:
                parsed = json.loads(json_text)

                for key in ["judgment", "answer", "response", "label"]:
                    if key in parsed:
                        value = parsed[key]
                        if isinstance(value, str):
                            value = value.strip().lower()
                            if value in allowed_judgments:
                                return value
            except Exception:
                pass

    lower_text = text.lower()

    regex_patterns = [
        r'"judgment"\s*:\s*"([^"]+)"',
        r"'judgment'\s*:\s*'([^']+)'",
        r'"answer"\s*:\s*"([^"]+)"',
        r'"response"\s*:\s*"([^"]+)"',
        r'"label"\s*:\s*"([^"]+)"'
    ]

    for pattern in regex_patterns:
        matches = re.findall(pattern, lower_text, re.DOTALL)
        for value in matches:
            value = value.strip().lower()
            if value in allowed_judgments:
                return value

    if re.search(r"\bthe assigned label is not appropriate\b", lower_text):
        return "no"

    if re.search(r"\bthe label is not appropriate\b", lower_text):
        return "no"

    if re.search(r"\bit is not appropriate\b", lower_text):
        return "no"

    if re.search(r"\bjudgment\s*[:\-]?\s*no\b", lower_text):
        return "no"

    if re.search(r"\banswer\s*[:\-]?\s*no\b", lower_text):
        return "no"

    if re.search(r"\bresponse\s*[:\-]?\s*no\b", lower_text):
        return "no"

    if re.search(r"\bthe assigned label is appropriate\b", lower_text):
        return "yes"

    if re.search(r"\bthe label is appropriate\b", lower_text):
        return "yes"

    if re.search(r"\bit is appropriate\b", lower_text):
        return "yes"

    if re.search(r"\bjudgment\s*[:\-]?\s*yes\b", lower_text):
        return "yes"

    if re.search(r"\banswer\s*[:\-]?\s*yes\b", lower_text):
        return "yes"

    if re.search(r"\bresponse\s*[:\-]?\s*yes\b", lower_text):
        return "yes"

    return ""


def main():
    """
    Run the LLM-based label judgment pipeline.
    The script reads the judge input dataset, validates the required columns, 
    sends each issue and assigned label to the configured Ollama model, extracts the model judgment, and saves the results to a CSV file.
    """
    df = pd.read_csv(INPUT_FILE)
    required_cols = [URL_COL, TITLE_COL, BODY_COL, LABEL_GIVEN_COL, GROUNDTRUTH_COL]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Colonne mancanti nel dataset input: {missing_cols}")

    results = []

    for idx, row in df.iterrows():
        issue_url = row.get(URL_COL, "")
        issue_title = row.get(TITLE_COL, "")
        issue_body = row.get(BODY_COL, "")
        label_given = row.get(LABEL_GIVEN_COL, "")
        correct_label = row.get(GROUNDTRUTH_COL, "")

        title = "" if pd.isna(issue_title) else str(issue_title)
        body = "" if pd.isna(issue_body) else str(issue_body)
        assigned_label_input = "" if pd.isna(label_given) else str(label_given).strip().lower()
        correct_label_value = "" if pd.isna(correct_label) else str(correct_label).strip().lower()

        prompt = build_prompt(title, body, assigned_label_input)

        result_row = {
            URL_COL: issue_url,
            TITLE_COL: title,
            BODY_COL: body,
            LABEL_GIVEN_COL: assigned_label_input,
            GROUNDTRUTH_COL: correct_label_value,
        }

        try:
            raw_output = query_ollama(prompt)
            llm_judgment = extract_judgment(raw_output)

            result_row["risposta_LLM"] = llm_judgment
            result_row["model_error"] = "" if llm_judgment else "Unable to parse judgment from model output"

        except Exception as e:
            result_row["risposta_LLM"] = ""
            result_row["model_error"] = str(e)

        results.append(result_row)

        if idx % 25 == 0:
            print(f"Processed {idx} rows")

        time.sleep(SLEEP_SECONDS)

    out_df = pd.DataFrame(results)[
        [URL_COL, TITLE_COL, BODY_COL, LABEL_GIVEN_COL, GROUNDTRUTH_COL, "risposta_LLM", "model_error"]
    ]
    out_df.to_csv(OUTPUT_FILE, index=False)

    print("Done.")
    print(f"Saved: {OUTPUT_FILE}")

if __name__ == "__main__":
    main()


