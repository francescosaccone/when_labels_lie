import pandas as pd
import requests
import json
import time
import os
import re

"""
Classify GitHub issue reports using a local Ollama language model.

This script processes a CSV file containing GitHub issue data, including the
issue URL, title, and body. For each issue, it builds a classification prompt
and sends it to the configured local Ollama model. The model is asked to assign
exactly one label among: bug, enhancement, or question.

The input CSV file is defined by INPUT_FILE and can be changed depending on the
dataset to process, for example correctly classified issues or misclassified
issues. The output CSV file is defined by OUTPUT_FILE and should be updated
according to the dataset and model being used.

The model is configured through OLLAMA_MODEL and can be changed to compare
different local models. The Ollama endpoint is configured through OLLAMA_URL.

The output CSV contains the original issue URL, title, body, the label assigned
by the model, and a model_error field reporting parsing or request errors.
"""




INPUT_FILE = "in_csv/subdataset_correct_minimal.csv"   
OUTPUT_FILE = "out_csv/model_output_correct_llama3.csv"


OLLAMA_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = " koesn/llama3-8b-instruct"


URL_COL = "issue_URL"
TITLE_COL = "issue_title"
BODY_COL = "issue_body"

REQUEST_TIMEOUT = 300
SLEEP_SECONDS = 0.1


import os
os.makedirs("out_csv", exist_ok=True)



LABEL_LIST = ["bug", "enhancement", "question"]

LABEL_DESCRIPTION = """
The "bug" label is used to identify an issue report that describes a promblem or error within the software or codebase. It indicates that something is not functioning as intended or producing unexpected results. Bug reports help developers identify and fix issues to improve the overall quality and reliability of the software. 

The "enhancement" label indicates new feature requests. It indicates that the reported issue is not related to a clear problem or bug, but rather an opportunity to add functionality or improve the existing behavior, usability, or performance. Enhancements requests help developers prioritize valuable additions and evolve the software over time. 

The "question" label is used when a user or contributor has a query or needs clarification regarding the software or codebase. It indicates that the issue report is seekeing information, guidance, or assistance. Questions can be related to functionality, usage, best practices, or any other topic that requires clarification. 

"""


def build_prompt(title: str, body: str) -> str:
    """
    Build the prompt used to classify a GitHub issue.
    Parameters
    ----------
    title : str
        GitHub issue title.
    body : str
        GitHub issue body.
    Returns
    -------
    str
        Prompt to send to the local Ollama model.
    """

    prompt = f"""
    You are provided with a GitHub issue in this format: 
    TITLE: \"\"\"{title}\"\"\"

    BODY: \"\"\"{body}\"\"\"

    You have to assign it a label. 
    Possible label are: {LABEL_LIST}

    {LABEL_DESCRIPTION}

    Title: \"\"\"{title}\"\"\"
    Body: \"\"\"{body}\"\"\"

    #INSTRUCTION
    Select the label strictly and exclusively from the following label list: bug, enhancement, question.
    The output must be ONLY a markdown code snippet formatted exactly like this:
   

    ```json
    {{
    "label": "string"
    }}

""".strip()
    return prompt



def query_ollama(prompt: str) -> str:
    """
    Send a prompt to the local Ollama model and return the generated text.
        Parameters
    ----------
    prompt : str
        Prompt to send to Ollama.
    Returns
    -------
    str
        Raw text response generated by the model.
    Raises
    ------
    requests.HTTPError
        If the HTTP request fails.
    requests.RequestException
        If the request cannot be completed.
    """
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0
        }
    }

    response = requests.post(
        OLLAMA_URL,
        json=payload,
        timeout=REQUEST_TIMEOUT
    )

    
    response.raise_for_status()

    data = response.json()
    import pprint
    print("\nMODEL TEXT RESPONSE ")
    print(data.get("response", ""))
    return data.get("response", "").strip()





def extract_label(raw_output: str) -> str:
    """
    Extract the assigned label from the model output.The function first tries to read a JSON object inside a markdown JSON code
    block. If no code block is found, it tries to parse the whole output as JSON.
    Parameters
    ----------
    raw_output : str
        Raw text generated by the model.
    Returns
    -------
    str
    Extracted label if parsing succeeds, otherwise an empty string.
    """
    if not isinstance(raw_output, str) or not raw_output.strip():
        return ""

    match = re.search(r"```json\s*(\{.*?\})\s*```", raw_output, re.DOTALL)
    json_text = match.group(1) if match else raw_output.strip()

    try:
        parsed = json.loads(json_text)
        label = parsed.get("label", "")
        return label.strip() if isinstance(label, str) else ""
    except Exception:
        return ""


def main():
    df = pd.read_csv(INPUT_FILE)

    required_cols = [URL_COL, TITLE_COL, BODY_COL]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Colonne mancanti nel dataset input: {missing_cols}")

    results = []

    for idx, row in df.iterrows():
        issue_url = row.get(URL_COL, "")
        issue_title = row.get(TITLE_COL, "")
        issue_body = row.get(BODY_COL, "")

        title = "" if pd.isna(issue_title) else str(issue_title)
        body = "" if pd.isna(issue_body) else str(issue_body)

        prompt = build_prompt(title, body)

        result_row = {
            URL_COL: issue_url,
            TITLE_COL: title,
            BODY_COL: body,
        }

        try:
            raw_output = query_ollama(prompt)
            assigned_label = extract_label(raw_output)

            result_row["assigned_label"] = assigned_label
            result_row["model_error"] = "" if assigned_label else "Unable to parse label from model output"

        except Exception as e:
            result_row["assigned_label"] = ""
            result_row["model_error"] = str(e)

        results.append(result_row)

        if idx % 25 == 0:
            print(f"Processed {idx} rows")

        time.sleep(SLEEP_SECONDS)

    out_df = pd.DataFrame(results)[[URL_COL, TITLE_COL, BODY_COL, "assigned_label", "model_error"]]
    out_df.to_csv(OUTPUT_FILE, index=False)

    print("Done.")
    print(f"Saved: {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
