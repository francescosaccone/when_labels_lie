#!/usr/bin/env python3
"""Test possible verbatim memorization of CORRECT or MISS GitHub issue bodies.

For every issue, send its title and the first half of its original body to a
local Ollama model and ask it to generate only the missing continuation.

Compare ONLY:
    - the original second half (hidden from the model), and
    - the continuation generated by the model.

Both texts are converted to sets of SHA-256 hashes of consecutive, normalized
N-word n-grams. The intersection gives the number of matching n-grams.
The per-issue matching percentage uses the distinct n-grams from the hidden
half as its denominator. The dataset-level matching rate counts issues with at
least one matching n-gram among successfully evaluated issues.

The first half is excluded from the primary comparison; a separate diagnostic
checks which matching n-grams also appear in the visible first half. One CSV is saved per
dataset, configured Ollama model, and n-gram size. Change OLLAMA_MODEL and rerun for other models.
Use --dataset correct or --dataset miss to select the issue cohort.
Use --ngram-size 8, 10, or 13 to select the tested word sequence length.
Use --all-ngrams to generate once (8-word minimum), then report 8/10/13.
The same model continuation is reused for all three n-gram sizes.

Default input and output directories are relative to the script location, not
hard-coded to any user's machine. Use --input-file to override the input path.
The label columns, if present, are ignored: only title and body enter the prompt.

An exact match is a possible memorization signal, not proof that an issue was
present in the model's training data. No match cannot rule out prior exposure.

Dependencies: pandas, requests
"""

import argparse
import csv
import hashlib
import re
import time

from pathlib import Path

import pandas as pd
import requests


# Resolve repository-relative files from this script's directory, regardless of
# the current working directory used to launch the program.
BASE_DIR = Path(__file__).resolve().parent

# File configuration. Both cohorts use the same CSV columns and experiment.
DATASET = "correct"
INPUT_FILE = BASE_DIR / "out_step_2" / f"judge_input_{DATASET}.csv"
NGRAM_SIZE = 13
OUT_DIR = BASE_DIR / f"out_memorization_{DATASET}_{NGRAM_SIZE}gram"

# Ollama configuration: change this value for each model.
OLLAMA_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = "koesn/llama3-8b-instruct"

# Keep this output separate from previous full-body comparison results.
MODEL_FILE_NAME = re.sub(r"[^a-zA-Z0-9._-]+", "_", OLLAMA_MODEL)
OUTPUT_FILE = OUT_DIR / f"memorization_second_half_{NGRAM_SIZE}gram_{MODEL_FILE_NAME}.csv"

URL_COL = "issue_URL"
TITLE_COL = "issue_title"
BODY_COL = "issue_body"

REQUEST_TIMEOUT = 300
SLEEP_SECONDS = 0.1
NUM_CTX = 8192
NUM_PREDICT = 1024
RANDOM_STATE = 42

# An n-gram is a sequence of words, not characters or model tokens.
WORD_PATTERN = re.compile(r"\b\w+\b", flags=re.UNICODE)


def output_columns() -> list:
    """Build result CSV column names for the configured n-gram length."""
    return [
        URL_COL,
        TITLE_COL,
        "model",
        "first_half_body",
        "original_second_half_body",
        "model_continuation",
        f"original_second_half_{NGRAM_SIZE}gram_count",
        f"model_continuation_{NGRAM_SIZE}gram_count",
        f"matching_{NGRAM_SIZE}gram_count",
        f"matching_{NGRAM_SIZE}gram_percentage",
        "status",
        "model_error",
    ]


def split_body(body: str) -> tuple:
    """Split a body near its word midpoint, without splitting any word.

    Returns:
        (first_half, second_half). Concatenating them reproduces the original
        string exactly. The second half is never included in the prompt.
    """
    matches = list(WORD_PATTERN.finditer(body))
    if not matches:
        return "", body

    midpoint = len(matches) // 2
    cut = matches[midpoint].start()
    return body[:cut], body[cut:]


def build_prompt(title: str, first_half: str) -> str:
    """Ask the LLM to supply only the missing continuation of the issue body."""
    return f"""Complete the following GitHub issue body as accurately as possible.

You have the issue title and the first half of its body.
Continue the original body from the exact point where the text stops.
Write ONLY the missing continuation. Do not repeat the text provided.
Do not add an introduction, explanation, label, heading, or Markdown fences.

ISSUE TITLE:
{title}

FIRST HALF OF ISSUE BODY:
{first_half}

MISSING CONTINUATION:
""".strip()


def query_ollama(prompt: str) -> str:
    """Send a prompt to the selected local Ollama model and return its text."""
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0,
            "seed": RANDOM_STATE,
            "num_ctx": NUM_CTX,
            "num_predict": NUM_PREDICT,
        },
    }
    response = requests.post(OLLAMA_URL, json=payload, timeout=REQUEST_TIMEOUT)
    response.raise_for_status()
    return response.json().get("response", "").strip()


def hashed_ngrams(text: str) -> set:
    """Return SHA-256 hashes of each distinct normalized N-word sequence."""
    words = WORD_PATTERN.findall(text.casefold())
    return {
        hashlib.sha256(" ".join(words[i:i + NGRAM_SIZE]).encode("utf-8")).hexdigest()
        for i in range(len(words) - NGRAM_SIZE + 1)
    }


def compare_second_half(original_second_half: str, model_continuation: str) -> dict:
    """Compare only the hidden original half against the generated continuation."""
    original_hashes = hashed_ngrams(original_second_half)
    generated_hashes = hashed_ngrams(model_continuation)
    matching_hashes = original_hashes.intersection(generated_hashes)

    return {
        f"original_second_half_{NGRAM_SIZE}gram_count": len(original_hashes),
        f"model_continuation_{NGRAM_SIZE}gram_count": len(generated_hashes),
        f"matching_{NGRAM_SIZE}gram_count": len(matching_hashes),
        f"matching_{NGRAM_SIZE}gram_percentage": (
            round(100 * len(matching_hashes) / len(original_hashes), 2)
            if original_hashes else ""
        ),
    }



def summarize_results(csv_file: str) -> dict:
    """Report hidden-half overlaps, including matches present in the first half.

    Supports both the current hidden-half results and older full-body result
    files that preserve the original body and generated continuation. Statistics
    are recomputed from text rather than trusting preexisting score columns.

    A match absent from the first half is a stronger signal of verbatim recall, but
    even this is not proof that the issue appeared in model training data.
    """
    df = pd.read_csv(csv_file).fillna("")
    required = [URL_COL, "first_half_body", "model_continuation", "status"]
    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"Missing columns in results CSV: {missing}")

    if "original_second_half_body" not in df.columns:
        if "original_body" not in df.columns:
            raise ValueError(
                "Results CSV needs 'original_second_half_body' or 'original_body'."
            )
        df["original_second_half_body"] = df["original_body"].apply(
            lambda body: split_body(str(body))[1]
        )

    # Recalculate every comparison using only the hidden body and continuation.
    successful_percentages = []
    total_matching_hashes = 0
    repeated_prompt_hashes = 0
    new_matching_hashes = 0
    positive_issues = 0
    new_positive_issues = 0
    not_testable = 0
    empty_responses = 0
    request_errors = 0
    other_failures = 0
    successful = 0

    for _, row in df.iterrows():
        hidden = str(row["original_second_half_body"])
        first_half = str(row["first_half_body"])
        continuation = str(row["model_continuation"])
        status = str(row["status"])

        if len(WORD_PATTERN.findall(hidden)) < NGRAM_SIZE:
            not_testable += 1
            continue
        if status == "request_error":
            request_errors += 1
            continue
        if status == "empty_model_response" or not continuation.strip():
            empty_responses += 1
            continue
        if status != "success":
            other_failures += 1
            continue

        hidden_hashes = hashed_ngrams(hidden)
        completion_hashes = hashed_ngrams(continuation)
        first_half_hashes = hashed_ngrams(first_half)
        matches = hidden_hashes & completion_hashes
        already_visible = matches & first_half_hashes
        not_in_first_half = matches - first_half_hashes

        successful += 1
        successful_percentages.append(100.0 * len(matches) / len(hidden_hashes))
        total_matching_hashes += len(matches)
        repeated_prompt_hashes += len(already_visible)
        new_matching_hashes += len(not_in_first_half)
        positive_issues += bool(matches)
        new_positive_issues += bool(not_in_first_half)

    def percentage(num: int, denom: int) -> float:
        return round(100.0 * num / denom, 2) if denom else 0.0

    sorted_percentages = sorted(successful_percentages)
    if sorted_percentages:
        n = len(sorted_percentages)
        median = (sorted_percentages[(n - 1) // 2] + sorted_percentages[n // 2]) / 2
        mean = sum(sorted_percentages) / n
    else:
        mean = median = 0.0

    model_names = [str(value) for value in df.get("model", pd.Series(dtype=str)).unique()]
    model_name = ", ".join(model_names) if model_names else "Unknown"
    summary = {
        "model": model_name,
        "total_issues": len(df),
        "successful_comparisons": successful,
        f"not_testable_second_half_under_{NGRAM_SIZE}_words": not_testable,
        "empty_model_responses": empty_responses,
        "request_errors": request_errors,
        "other_failures": other_failures,
        "issues_without_matches": successful - positive_issues,
        "issues_with_matching_hidden_ngrams": positive_issues,
        "issues_with_matching_hidden_ngrams_pct": percentage(positive_issues, successful),
        "total_matching_ngrams_per_issue": total_matching_hashes,
        "matching_ngrams_already_in_first_half": repeated_prompt_hashes,
        "matching_ngrams_not_in_first_half": new_matching_hashes,
        "issues_with_matches_not_in_first_half": new_positive_issues,
        "issues_with_matches_not_in_first_half_pct": percentage(new_positive_issues, successful),
        "mean_matching_percentage": round(mean, 2),
        "median_matching_percentage": round(median, 2),
    }

    lines = [
        f"=== SECOND-HALF {NGRAM_SIZE}-GRAM MEMORIZATION SUMMARY ===",
        f"Model: {model_name}",
        f"Total issues: {summary['total_issues']}",
        f"Successful comparisons: {successful}",
        f"Not testable (hidden half < {NGRAM_SIZE} words): {not_testable}",
        f"Empty model responses: {empty_responses}",
        f"Request errors: {request_errors}",
        f"Other failures: {other_failures}",
        "",
        "--- Hidden-half vs. generated-continuation overlap ---",
        f"Issues with >= 1 matching {NGRAM_SIZE}-gram: {positive_issues}/{successful} "
        f"({summary['issues_with_matching_hidden_ngrams_pct']:.2f}%)",
        f"Issues with no matching {NGRAM_SIZE}-grams: {successful - positive_issues}",
        f"Mean matching percentage: {mean:.2f}%",
        f"Median matching percentage: {median:.2f}%",
        f"Total matching distinct {NGRAM_SIZE}-grams (summed per issue): {total_matching_hashes}",
        "",
        "--- How many matches were already present in the first half? ---",
        f"Matching {NGRAM_SIZE}-grams also in first half: {repeated_prompt_hashes}",
        f"Matching {NGRAM_SIZE}-grams absent from first half: {new_matching_hashes}",
        f"Issues with >= 1 match absent from first half: {new_positive_issues}/{successful} "
        f"({summary['issues_with_matches_not_in_first_half_pct']:.2f}%)",
        "",
        "Interpretation: Overlap absent from the first half is a possible signal",
        "of verbatim memorization, but also from repeated or conventional text/code.",
        "No overlap does not prove that training-data exposure did not occur.",
    ]
    report = "\n".join(lines)
    print("\n" + report)

    base_path = Path(csv_file)
    # Include the evaluated n-gram size: reports derived from one 8-gram
    # response CSV must not overwrite each other.
    txt_path = base_path.with_name(
        f"{base_path.stem}.summary_{NGRAM_SIZE}gram.txt"
    )
    summary_csv_path = base_path.with_name(
        f"{base_path.stem}.summary_{NGRAM_SIZE}gram.csv"
    )
    txt_path.write_text(report + "\n", encoding="utf-8")
    pd.DataFrame([summary]).to_csv(summary_csv_path, index=False)
    print(f"Summary saved: {txt_path}")
    print(f"Summary CSV saved: {summary_csv_path}")
    return summary



def configure_run(size: int, dataset: str, input_file: str | None = None) -> None:
    """Select cohort, n-gram size, input path and unique output paths."""
    global DATASET, INPUT_FILE, NGRAM_SIZE, OUT_DIR, OUTPUT_FILE
    if size < 1:
        raise ValueError("N-gram size must be a positive integer.")
    if dataset not in {"correct", "miss"}:
        raise ValueError("Dataset must be 'correct' or 'miss'.")
    DATASET = dataset
    # Default inputs are next to the script. Explicit --input-file paths are
    # interpreted normally (absolute or relative to the launching directory).
    INPUT_FILE = (
        Path(input_file)
        if input_file is not None
        else BASE_DIR / "out_step_2" / f"judge_input_{DATASET}.csv"
    )
    NGRAM_SIZE = size
    OUT_DIR = BASE_DIR / f"out_memorization_{DATASET}_{NGRAM_SIZE}gram"
    OUTPUT_FILE = OUT_DIR / (
        f"memorization_second_half_{NGRAM_SIZE}gram_{MODEL_FILE_NAME}.csv"
    )


def main() -> None:
    """Process selected issues, compare hidden continuations, and export results."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(INPUT_FILE)

    required_columns = [URL_COL, TITLE_COL, BODY_COL]
    missing_columns = [col for col in required_columns if col not in df.columns]
    if missing_columns:
        raise ValueError(f"Missing columns in {INPUT_FILE}: {missing_columns}")

    normalized_urls = df[URL_COL].fillna("").astype(str).str.strip().str.rstrip("/")
    if normalized_urls.eq("").any() or normalized_urls.duplicated().any():
        raise ValueError(f"{DATASET.upper()} input must contain non-empty, unique issue URLs.")

    print(f"Dataset: {DATASET.upper()}")
    print(f"Input file: {INPUT_FILE}")
    print(f"Model: {OLLAMA_MODEL}")
    print(f"Input issues: {len(df)}")
    print("Comparison: original second half vs. generated continuation")
    print(f"N-gram size: {NGRAM_SIZE} consecutive normalized words (SHA-256)")

    # Write one result at a time to retain completed rows if execution stops.
    # Rerunning the same model overwrites that model's previous output CSV.
    with open(OUTPUT_FILE, "w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=output_columns())
        writer.writeheader()

        for position, (_, row) in enumerate(df.iterrows(), start=1):
            title = "" if pd.isna(row[TITLE_COL]) else str(row[TITLE_COL])
            body = "" if pd.isna(row[BODY_COL]) else str(row[BODY_COL])
            first_half, second_half = split_body(body)

            result = {
                URL_COL: str(row[URL_COL]),
                TITLE_COL: title,
                "model": OLLAMA_MODEL,
                "first_half_body": first_half,
                "original_second_half_body": second_half,
                "model_continuation": "",
                f"original_second_half_{NGRAM_SIZE}gram_count": "",
                f"model_continuation_{NGRAM_SIZE}gram_count": "",
                f"matching_{NGRAM_SIZE}gram_count": "",
                f"matching_{NGRAM_SIZE}gram_percentage": "",
                "status": "",
                "model_error": "",
            }

            # Fewer than N words in the hidden half makes an N-gram
            # comparison impossible. Do not count these issues as no-match.
            if len(WORD_PATTERN.findall(second_half)) < NGRAM_SIZE:
                result["status"] = f"not_testable_second_half_under_{NGRAM_SIZE}_words"
            else:
                try:
                    continuation = query_ollama(build_prompt(title, first_half))
                    result["model_continuation"] = continuation
                    if not continuation:
                        result["status"] = "empty_model_response"
                    else:
                        result.update(compare_second_half(second_half, continuation))
                        result["status"] = "success"
                except Exception as error:
                    result["status"] = "request_error"
                    result["model_error"] = str(error)
                time.sleep(SLEEP_SECONDS)

            writer.writerow(result)
            file.flush()

            if position % 25 == 0 or position == len(df):
                print(f"Processed: {position}/{len(df)}")

    print(f"\nResults saved: {OUTPUT_FILE}")
    summarize_results(OUTPUT_FILE)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Generate and summarize hidden-half N-gram memorization results."
    )
    parser.add_argument(
        "--report-only",
        metavar="EXISTING_CSV",
        help="Recalculate and print a summary from an existing results CSV "
             "without making any model requests.",
    )
    parser.add_argument(
        "--ngram-size",
        type=int,
        default=13,
        choices=[8, 10, 13],
        help="Number of consecutive words per n-gram (default: 13).",
    )
    parser.add_argument(
        "--all-ngrams",
        action="store_true",
        help="Query Ollama once per eligible issue for 8-grams, then calculate "
             "8-, 10- and 13-gram summaries from the same continuations.",
    )
    parser.add_argument(
        "--dataset",
        choices=["correct", "miss"],
        default="correct",
        help="Issue cohort to evaluate (default: correct).",
    )
    parser.add_argument(
        "--input-file",
        default=None,
        metavar="PATH",
        help="Override the input CSV path. By default, read "
             "out_step_2/judge_input_<dataset>.csv beside this script.",
    )
    args = parser.parse_args()
    if args.all_ngrams and args.ngram_size != 13:
        parser.error("--all-ngrams cannot be combined with --ngram-size.")

    # Generate responses for every issue with >= 8 hidden words, then compute
    # 10- and 13-gram scores using EXACTLY the same generated continuations.
    # Using the 8-gram baseline is important: 13-gram-first generation skips
    # some issues that are testable with 8 or 10 words.
    generation_n = 8 if args.all_ngrams else args.ngram_size
    configure_run(generation_n, args.dataset, args.input_file)
    if args.report_only:
        report_csv = args.report_only
        if args.all_ngrams:
            for n in (8, 10, 13):
                configure_run(n, args.dataset, args.input_file)
                summarize_results(report_csv)
        else:
            summarize_results(report_csv)
    else:
        main()
        if args.all_ngrams:
            generated_csv = OUTPUT_FILE
            for n in (10, 13):
                configure_run(n, args.dataset, args.input_file)
                summarize_results(generated_csv)
